export const LANG_NAMES = {
  en: 'English',
  ru: 'Русский',
  uz: 'Oʼzbekcha',
  'uz-cyrl': 'Ўзбекча',
  kaa: 'Qaraqalpaqsha',
};

const KEY = 'sb-lang';  // shared with the marketing site

function norm(tag) {
  tag = String(tag || '').toLowerCase();
  if (tag.indexOf('kaa') === 0) return 'kaa';
  if (tag.indexOf('uz') === 0) return tag.indexOf('cyrl') !== -1 ? 'uz-cyrl' : 'uz';
  if (tag.indexOf('ru') === 0) return 'ru';
  if (tag.indexOf('en') === 0) return 'en';
  return null;
}

export let lang = 'en';

export function initLang() {
  let stored = null;
  try { stored = norm(localStorage.getItem(KEY)); } catch (e) { /* private mode */ }
  if (stored && STRINGS[stored]) { lang = stored; return; }
  const cands = navigator.languages || [navigator.language || ''];
  for (const c of cands) {
    const n = norm(c);
    if (n && STRINGS[n]) { lang = n; return; }
  }
}

export function setLang(l) {
  if (!STRINGS[l]) return;
  lang = l;
  try { localStorage.setItem(KEY, l); } catch (e) { /* private mode */ }
  applyStatic();
}

export function t(key, vars) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

/* Fill every element carrying data-i18n / data-i18n-ph. */
export function applyStatic() {
  document.documentElement.lang = lang;
  document.title = `RS Pixel — ${t('app.title')}`;
  for (const el of document.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of document.querySelectorAll('[data-i18n-ph]')) {
    el.placeholder = t(el.dataset.i18nPh);
  }
  for (const el of document.querySelectorAll('[data-i18n-title]')) {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', t(el.dataset.i18nTitle));
  }
}

/* Format tiyin as a so'm amount for the current language. */
export function fmtAmount(minor) {
  const sum = Math.round(minor / 100);
  return `${sum.toLocaleString('ru-RU')} ${t('cur')}`;
}
